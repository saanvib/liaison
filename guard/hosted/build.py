"""Flatten the Guard for hosted Agentverse (A11): python -m guard.hosted.build

Hosted Agentverse (probed 2026-10-17) imports sibling files but not folders, and
can't find data files next to the code. So this writes flat files with rewritten
imports (`from guard.core import` -> `from guard_core import`) and policy.json
embedded as Python:

    guard/hosted/dist/guard/         paste into the Guard's hosted agent
    guard/hosted/dist/smoke_client/  paste into a throwaway test agent

The repo layout and every local entry point are unchanged. Never edit dist/;
rebuild it.
"""
from __future__ import annotations

import argparse
import json
import pprint
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT / "guard" / "hosted" / "dist"

# dist name -> source path, relative to the repo root
GUARD_FILES = {
    "agent.py": "guard/hosted/entry.py",
    "contracts.py": "contracts/messages.py",
    "guard_agent.py": "guard/agent.py",
    "guard_core.py": "guard/core.py",
    "guard_rules.py": "guard/rules.py",
    "guard_judge.py": "guard/judge.py",
    "guard_grounding.py": "guard/grounding.py",
    "guard_llm.py": "guard/llm.py",
}
CLIENT_FILES = {
    "agent.py": "guard/hosted/smoke_client.py",
    "contracts.py": "contracts/messages.py",
    "guard_smoke_requests.py": "guard/smoke_requests.py",
}

_GUARD_IMPORT = re.compile(r"^(\s*)from guard\.(\w+) import ", re.MULTILINE)
_LEFTOVER = re.compile(r"^\s*(?:from|import) (?:guard|contracts|experts)\.|^\s*from \.", re.MULTILINE)
# Hosted modules have no __file__. Only a call-time use inside a function is safe (the embedded
# policy means it never runs); anything at module level crashes the agent on start.
_MODULE_LEVEL_FILE = re.compile(r"^[^\s#].*\b__file__\b", re.MULTILINE)
# Hosted runs Python 3.10 and doesn't put modules in sys.modules while they load. With string
# annotations, 3.10's dataclasses then does sys.modules.get(mod).__dict__ on None and the agent
# fails to start. Real annotations avoid that lookup, so the flat files drop the future import.
_FUTURE_ANNOTATIONS = re.compile(r"^from __future__ import annotations\n", re.MULTILINE)


class BuildError(Exception):
    pass


def flatten(source: str, origin: str) -> str:
    out = _FUTURE_ANNOTATIONS.sub("", _GUARD_IMPORT.sub(r"\1from guard_\2 import ", source))
    leftover = _LEFTOVER.search(out)
    if leftover:
        raise BuildError(f"{origin}: import not flattened: {leftover.group(0).strip()!r}")
    uses_file = _MODULE_LEVEL_FILE.search(out)
    if uses_file:
        raise BuildError(f"{origin}: __file__ at module level (undefined hosted): {uses_file.group(0).strip()!r}")
    return f"# Generated by `python -m guard.hosted.build` from {origin}. Do not edit; rebuild.\n" + out


def policy_module(policy_path: Path) -> str:
    policy = json.loads(policy_path.read_text())
    return (
        "# Generated by `python -m guard.hosted.build` from guard/policy.json. Do not edit; rebuild.\n"
        '"""guard/policy.json embedded as Python: hosted agents can\'t read data files."""\n\n'
        f"POLICY = {pprint.pformat(policy, width=110, sort_dicts=False)}\n"
    )


def _write(target: Path, files: dict[str, str]) -> list[str]:
    target.mkdir(parents=True)
    for name, origin in files.items():
        (target / name).write_text(flatten((ROOT / origin).read_text(), origin))
    return list(files)


def build(out: Path = DEFAULT_OUT) -> dict[str, list[str]]:
    if out.exists():
        shutil.rmtree(out)
    guard_names = _write(out / "guard", GUARD_FILES)
    (out / "guard" / "guard_policy.py").write_text(policy_module(ROOT / "guard" / "policy.json"))
    client_names = _write(out / "smoke_client", CLIENT_FILES)
    return {"guard": guard_names + ["guard_policy.py"], "smoke_client": client_names}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    try:
        built = build(args.out)
    except BuildError as e:
        print(f"build failed: {e}", file=sys.stderr)
        return 1
    for folder, names in built.items():
        print(f"{args.out / folder}/  ({len(names)} files)")
        for name in names:
            print(f"    {name}")
    print("\nPaste each file into a hosted agent's editor under the same name (agent.py replaces the"
          "\ngenerated one). Secrets and the full checklist: guard/NOTES.md, 'Deploying to hosted Agentverse'.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
