"""The flattened hosted build runs like hosted Agentverse: separate interpreter, flat
files only (the repo's packages aren't importable), `agent` predefined, secrets as
env vars, no policy.json on disk."""
import json
import os
import subprocess
import sys

import pytest

from guard.hosted.build import BuildError, build, flatten

# Runs inside the dist folder. Prints one JSON object with what the handlers did.
RUNNER = r"""
import asyncio, importlib.util, json, logging, os, sys
sys.path.insert(0, os.getcwd())
assert importlib.util.find_spec("guard") is None, "repo packages leaked onto sys.path"
assert not os.path.exists("policy.json")

from uagents import Agent

class Ctx:
    def __init__(self, agent):
        self.agent, self.sent, self.logger = agent, [], logging.getLogger("ctx")
    async def send(self, dest, msg):
        self.sent.append((dest, json.loads(msg.json())))

async def main():
    import inspect
    quiet = {"report_events": False} if "report_events" in inspect.signature(Agent).parameters else {}  # absent in 0.25 (hosted)
    agent = Agent(name="hosted-sim", seed="liaison-dev-only hosted sim", **quiet)
    ns = {"agent": agent, "__name__": "__hosted__"}
    exec(compile(open("agent.py").read(), "agent.py", "exec"), ns)
    ctx = Ctx(agent)
    out = {"names": sorted(k for k in ns if not k.startswith("_"))}
    if "on_guard_request" in ns:
        from contracts import GuardRequest, Source
        await ns["report_config"](ctx)
        from guard_smoke_requests import REQUESTS
        for req in REQUESTS:
            await ns["on_guard_request"](ctx, "agent1vendor", req)
        await ns["on_guard_request"](ctx, "agent1stranger", REQUESTS[0])
    else:
        await ns["send_requests"](ctx)
    out["sent"] = ctx.sent
    print(json.dumps(out))

asyncio.run(main())
"""


def _run(folder, extra_env=None, extra_files=()):
    env = {k: v for k, v in os.environ.items() if not k.startswith(("LLM_", "ALLOWED_", "GUARD_"))}
    env.update(extra_env or {})
    proc = subprocess.run(
        [sys.executable, "-I", "-c", RUNNER], cwd=folder, env=env, capture_output=True, text=True, timeout=120
    )
    assert proc.returncode == 0, proc.stderr[-3000:]
    return json.loads(proc.stdout.strip().splitlines()[-1])


@pytest.fixture(scope="module")
def dist(tmp_path_factory):
    out = tmp_path_factory.mktemp("hosted") / "dist"
    build(out)
    # The runner reuses the smoke requests; hosted, the Guard folder doesn't need them.
    (out / "guard" / "guard_smoke_requests.py").write_text((out / "smoke_client" / "guard_smoke_requests.py").read_text())
    return out


def test_build_writes_flat_files_only(dist):
    for folder in ("guard", "smoke_client"):
        paths = list((dist / folder).iterdir())
        assert all(p.is_file() and p.suffix == ".py" for p in paths), paths
        for p in paths:
            text = p.read_text()
            assert "from guard." not in text and "import guard." not in text, p.name
            assert text.startswith("# Generated by"), p.name


def test_hosted_guard_answers_all_modes_and_drops_strangers(dist):
    out = _run(dist / "guard", {"ALLOWED_SENDERS": "agent1vendor"})
    replies = {msg["request_id"]: (dest, msg["verdict"], msg["category"]) for dest, msg in out["sent"]}
    assert replies == {
        "smoke-screen": ("agent1vendor", "blocked", "patient_data"),
        "smoke-draft": ("agent1vendor", "needs_review", "none"),  # no LLM_API_KEY: judge off, fails closed
        "smoke-egress": ("agent1vendor", "blocked", "pricing_contract"),
    }
    assert len(out["sent"]) == 3  # the stranger got nothing


def test_hosted_guard_with_empty_allowlist_drops_everything(dist):
    assert _run(dist / "guard")["sent"] == []


def test_hosted_smoke_client_sends_one_request_per_mode(dist):
    out = _run(dist / "smoke_client", {"GUARD_ADDRESS": "agent1guard"})
    assert [(dest, msg["request_id"]) for dest, msg in out["sent"]] == [
        ("agent1guard", "smoke-screen"), ("agent1guard", "smoke-draft"), ("agent1guard", "smoke-egress")]


def test_flatten_rejects_imports_it_cannot_rewrite():
    with pytest.raises(BuildError):
        flatten("from .messages import X\n", "x.py")
    with pytest.raises(BuildError):
        flatten("import guard.core\n", "x.py")
    assert flatten("    from guard.llm import A\n", "x.py").endswith("    from guard_llm import A\n")
