"""Flatten the Vendor Agent for hosted Agentverse (A11): python -m vendor_agent.hosted.build

Hosted Agentverse (per Person 2's probe, guard/NOTES.md) imports sibling files
but not folders, and can't find data files next to the code. So this writes
flat files with rewritten imports (`from vendor_agent.core import` ->
`from vendor_agent_core import`):

    vendor_agent/hosted/dist/vendor/   paste into the Vendor Agent's hosted agent

docs_seed/ is not embedded: seed it after the hosted agent is running with
`python -m vendor_agent.ingest vendor_agent/docs_seed` (no --direct) pointed
at its real address, over the network, same as any other IngestDocument.

The repo layout and every local entry point are unchanged. Never edit dist/;
rebuild it.
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT / "vendor_agent" / "hosted" / "dist"

# dist name -> source path, relative to the repo root
VENDOR_FILES = {
    "agent.py": "vendor_agent/hosted/entry.py",
    "contracts.py": "contracts/messages.py",
    "vendor_agent_config.py": "vendor_agent/config.py",
    "vendor_agent_clients.py": "vendor_agent/clients.py",
    "vendor_agent_texts.py": "vendor_agent/texts.py",
    "vendor_agent_models.py": "vendor_agent/models.py",
    "vendor_agent_retrieval.py": "vendor_agent/retrieval.py",
    "vendor_agent_kb.py": "vendor_agent/kb.py",
    "vendor_agent_core.py": "vendor_agent/core.py",
    "vendor_agent_agent.py": "vendor_agent/agent.py",
}

_VENDOR_IMPORT = re.compile(r"^(\s*)from vendor_agent\.(\w+) import ", re.MULTILINE)
_LEFTOVER = re.compile(r"^\s*(?:from|import) (?:vendor_agent|contracts)\.|^\s*from \.", re.MULTILINE)
# Hosted modules have no __file__; only a call-time use inside a function is safe.
_MODULE_LEVEL_FILE = re.compile(r"^[^\s#].*\b__file__\b", re.MULTILINE)
# Hosted runs Python 3.10 and doesn't put modules in sys.modules while they load. With string
# annotations, 3.10's dataclasses then does sys.modules.get(mod).__dict__ on None and the agent
# fails to start (seen for the Guard, 2026-10-17). The flat files drop the future import.
_FUTURE_ANNOTATIONS = re.compile(r"^from __future__ import annotations\n", re.MULTILINE)


class BuildError(Exception):
    pass


def flatten(source: str, origin: str) -> str:
    out = _FUTURE_ANNOTATIONS.sub("", _VENDOR_IMPORT.sub(r"\1from vendor_agent_\2 import ", source))
    leftover = _LEFTOVER.search(out)
    if leftover:
        raise BuildError(f"{origin}: import not flattened: {leftover.group(0).strip()!r}")
    uses_file = _MODULE_LEVEL_FILE.search(out)
    if uses_file:
        raise BuildError(f"{origin}: __file__ at module level (undefined hosted): {uses_file.group(0).strip()!r}")
    return f"# Generated by `python -m vendor_agent.hosted.build` from {origin}. Do not edit; rebuild.\n" + out


def _write(target: Path, files: dict[str, str]) -> list[str]:
    target.mkdir(parents=True)
    for name, origin in files.items():
        (target / name).write_text(flatten((ROOT / origin).read_text(), origin))
    return list(files)


def build(out: Path = DEFAULT_OUT) -> dict[str, list[str]]:
    if out.exists():
        shutil.rmtree(out)
    vendor_names = _write(out / "vendor", VENDOR_FILES)
    return {"vendor": vendor_names}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    try:
        built = build(args.out)
    except BuildError as e:
        print(f"build failed: {e}", file=sys.stderr)
        return 1
    for folder, names in built.items():
        print(f"{args.out / folder}/  ({len(names)} files)")
        for name in names:
            print(f"    {name}")
    print("\nPaste each file into the hosted agent's editor under the same name (agent.py replaces the"
          "\ngenerated one). Secrets and the full checklist: vendor_agent/NOTES.md.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
